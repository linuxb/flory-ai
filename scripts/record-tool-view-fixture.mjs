// Records the cross-language tool-view conformance fixture.
//
// The expected encodings are produced by the TypeScript canonicaliser and then
// checked by the Go one, so the fixture is an assertion that the two agree
// rather than a transcript of whichever ran last. Run this only when adding a
// case; a change to an existing expectation means the encoders diverged, which
// is the defect the fixture exists to catch.
import {writeFile} from 'node:fs/promises';
import {canonicalize, digestOf, toolViewRef} from '../engine/src/tool-view.ts';

const canonicalValues = [
    {name: 'object keys are sorted', value: {beta: 1, alpha: {z: true, a: false}}},
    {name: 'array order is preserved', value: ['b', 'a', 'c']},
    {name: 'HTML characters stay unescaped', value: {description: 'quantity < 10 & rising'}},
    {name: 'control characters use short escapes', value: {detail: 'line\nnext\ttabbed'}},
    {name: 'a quote and a backslash', value: {detail: 'he said "\\" once'}},
    {name: 'non-ASCII is emitted literally', value: {owner: '库存团队', note: 'naïve'}},
    {name: 'empty containers', value: {tools: [], meta: {}}},
    {name: 'negative and zero integers', value: {offset: -17, zero: 0}},
    {name: 'nested arrays of objects', value: {items: [{b: 2, a: 1}, {c: 3}]}},
];

const rejectedValues = [
    {name: 'a fractional number', value: 1.5, reason: 'a float has no canonical text form'},
    {name: 'a fractional number in an object', value: {multiplier: 2.5}, reason: 'a float has no canonical text form'},
];

const reserveTool = {
    tool_id: 'inventory.reserve',
    tool_version: '1.0.0',
    description: 'Reserve inventory for an order',
    input_schema: {additionalProperties: false, properties: {order_id: {type: 'string'}, quantity: {type: 'integer'}, sku: {type: 'string'}}, required: ['sku', 'quantity'], type: 'object'},
    output_schema: {type: 'object'},
    route_id: 'inventory',
    adapter: {protocol: 'grpc', operation: 'flory.gateway.v1.ToolExecutionService/Execute'},
    txn: {
        effect_class: 'reversible',
        mode: 'tcc',
        idempotency_key_path: '$.order_id',
        idempotent_retryable: true,
        try_timeout_s: 900,
        confirm_tool: 'inventory.confirm',
        cancel_tool: 'inventory.release',
    },
    compensation_style: 'not-compensating',
    footprint: ['inventory:{sku}'],
    writes: ['inventory:{sku}'],
    timeout_ms: 15000,
    retry_constraints: {max_attempts: 3, initial_backoff_ms: 100, multiplier_milli: 2000, max_backoff_ms: 5000},
    owner: 'inventory-team',
};

const releaseTool = {
    tool_id: 'inventory.release',
    tool_version: '1.0.0',
    description: 'Release exactly the delta its matching reserve added',
    input_schema: {properties: {order_id: {type: 'string'}}, required: ['order_id'], type: 'object'},
    output_schema: {type: 'object'},
    route_id: 'inventory',
    adapter: {protocol: 'grpc', operation: 'flory.gateway.v1.ToolExecutionService/Execute'},
    txn: {effect_class: 'bufferable', mode: 'plain', idempotency_key_path: '$.order_id', idempotent_retryable: true},
    compensation_style: 'delta',
    footprint: ['inventory:{sku}'],
    writes: ['inventory:{sku}'],
    timeout_ms: 5000,
    retry_constraints: {max_attempts: 3, initial_backoff_ms: 100, multiplier_milli: 2000, max_backoff_ms: 5000},
    owner: 'inventory-team',
};

const confirmTool = {...releaseTool, tool_id: 'inventory.confirm', description: 'Commit the delta its matching reserve held', compensation_style: 'not-compensating'};

const views = [
    {name: 'an empty view', document: {tool_view_version: '1', tools: []}},
    {name: 'a complete tcc cluster', document: {tool_view_version: '1', tools: [confirmTool, releaseTool, reserveTool]}},
];

const fixture = {
    // eslint-disable-next-line @typescript-eslint/naming-convention
    _comment: 'Generated by scripts/record-tool-view-fixture.mjs. Both the Go and TypeScript canonical encoders must reproduce every expectation here.',
    canonical_cases: canonicalValues.map(({name, value}) => {
        const canonical = canonicalize(value);
        return {name, value, canonical, digest: digestOf(canonical)};
    }),
    rejected_cases: rejectedValues,
    view_cases: views.map(({name, document}) => {
        const canonical = canonicalize(document);
        const digest = digestOf(canonical);
        return {name, document, canonical, digest, ref: toolViewRef(digest)};
    }),
};

await writeFile(new URL('../test/fixtures/tool-view-conformance.json', import.meta.url), `${JSON.stringify(fixture, null, 4)}\n`);
process.stdout.write('recorded test/fixtures/tool-view-conformance.json\n');
